-- Read-only. Lists the live database structure as SQL text, one statement per row.
-- Used because Lovable Cloud gives no connection string for pg_dump.
-- Save the "ddl" column of every row, in order, to supabase/schema_snapshot.sql.
-- Sections: 1 extensions, 2 enums, 3 sequences, 4 tables, 5 keys/checks, 6 foreign keys,
-- 7 indexes, 8 views, 9 functions, 10 triggers, 11 RLS on, 12 policies,
-- 13 storage buckets, 14 storage policies, 15 realtime tables.
with
tbl as (
  select c.oid, c.relname, c.relrowsecurity, c.relforcerowsecurity
  from pg_class c join pg_namespace n on n.oid = c.relnamespace
  where n.nspname = 'public' and c.relkind in ('r', 'p')
),
stmts(section, object, ddl) as (
  select 1, e.extname::text,
    format('CREATE EXTENSION IF NOT EXISTS %I WITH SCHEMA %I;', e.extname, n.nspname)
  from pg_extension e join pg_namespace n on n.oid = e.extnamespace
  where e.extname <> 'plpgsql'

  union all
  select 2, t.typname::text,
    format('CREATE TYPE public.%I AS ENUM (%s);', t.typname,
      (select string_agg(quote_literal(e.enumlabel), ', ' order by e.enumsortorder)
       from pg_enum e where e.enumtypid = t.oid))
  from pg_type t join pg_namespace n on n.oid = t.typnamespace
  where n.nspname = 'public' and t.typtype = 'e'

  union all
  select 3, s.sequencename::text,
    format('CREATE SEQUENCE IF NOT EXISTS public.%I START %s INCREMENT %s; -- last_value: %s',
      s.sequencename, s.start_value, s.increment_by, coalesce(s.last_value::text, 'unused'))
  from pg_sequences s where s.schemaname = 'public'

  union all
  select 4, t.relname::text,
    format(E'CREATE TABLE public.%I (\n%s\n);', t.relname,
      (select string_agg(format('  %I %s%s%s%s', a.attname, format_type(a.atttypid, a.atttypmod),
          case a.attidentity when 'a' then ' GENERATED ALWAYS AS IDENTITY'
                             when 'd' then ' GENERATED BY DEFAULT AS IDENTITY' else '' end,
          case when a.attgenerated = 's' then ' GENERATED ALWAYS AS (' || pg_get_expr(d.adbin, d.adrelid) || ') STORED'
               when d.adbin is not null then ' DEFAULT ' || pg_get_expr(d.adbin, d.adrelid) else '' end,
          case when a.attnotnull then ' NOT NULL' else '' end), E',\n' order by a.attnum)
       from pg_attribute a
       left join pg_attrdef d on d.adrelid = a.attrelid and d.adnum = a.attnum
       where a.attrelid = t.oid and a.attnum > 0 and not a.attisdropped))
  from tbl t

  union all
  select case when c.contype = 'f' then 6 else 5 end, t.relname || '.' || c.conname,
    format('ALTER TABLE public.%I ADD CONSTRAINT %I %s;', t.relname, c.conname, pg_get_constraintdef(c.oid))
  from pg_constraint c join tbl t on t.oid = c.conrelid
  where c.contype in ('p', 'u', 'f', 'c', 'x')

  union all
  select 7, t.relname || '.' || ic.relname, pg_get_indexdef(i.indexrelid) || ';'
  from pg_index i
  join tbl t on t.oid = i.indrelid
  join pg_class ic on ic.oid = i.indexrelid
  where not exists (select 1 from pg_constraint c where c.conindid = i.indexrelid and c.conrelid = i.indrelid)

  union all
  select 8, c.relname::text,
    format(E'%s public.%I%s AS\n%s',
      case c.relkind when 'm' then 'CREATE MATERIALIZED VIEW' else 'CREATE OR REPLACE VIEW' end,
      c.relname,
      case when c.reloptions is not null then ' WITH (' || array_to_string(c.reloptions, ', ') || ')' else '' end,
      pg_get_viewdef(c.oid, true))
  from pg_class c join pg_namespace n on n.oid = c.relnamespace
  where n.nspname = 'public' and c.relkind in ('v', 'm')

  union all
  select 9, p.proname || '(' || pg_get_function_identity_arguments(p.oid) || ')',
    pg_get_functiondef(p.oid) || ';'
  from pg_proc p join pg_namespace n on n.oid = p.pronamespace
  where n.nspname = 'public' and p.prokind in ('f', 'p')
    and not exists (select 1 from pg_depend dep where dep.objid = p.oid and dep.deptype = 'e')

  union all
  select 10, cn.nspname || '.' || c.relname || '.' || tg.tgname,
    pg_get_triggerdef(tg.oid, true) || ';'
  from pg_trigger tg
  join pg_class c on c.oid = tg.tgrelid
  join pg_namespace cn on cn.oid = c.relnamespace
  join pg_proc p on p.oid = tg.tgfoid
  join pg_namespace pn on pn.oid = p.pronamespace
  where not tg.tgisinternal and (cn.nspname = 'public' or pn.nspname = 'public')

  union all
  select 11, t.relname::text,
    format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY;', t.relname)
    || case when t.relforcerowsecurity then format(' ALTER TABLE public.%I FORCE ROW LEVEL SECURITY;', t.relname) else '' end
  from tbl t where t.relrowsecurity

  union all
  select case when p.schemaname = 'public' then 12 else 14 end,
    p.schemaname || '.' || p.tablename || '.' || p.policyname,
    format('CREATE POLICY %I ON %I.%I AS %s FOR %s TO %s%s%s;',
      p.policyname, p.schemaname, p.tablename, p.permissive, p.cmd,
      (select string_agg(quote_ident(r), ', ') from unnest(p.roles) r),
      case when p.qual is not null then E'\n  USING (' || p.qual || ')' else '' end,
      case when p.with_check is not null then E'\n  WITH CHECK (' || p.with_check || ')' else '' end)
  from pg_policies p where p.schemaname in ('public', 'storage')

  union all
  select 13, b.id,
    format('INSERT INTO storage.buckets (id, name, public, file_size_limit, allowed_mime_types) VALUES (%L, %L, %L, %L, %L);',
      b.id, b.name, b.public, b.file_size_limit, b.allowed_mime_types)
  from storage.buckets b

  union all
  select 15, pt.schemaname || '.' || pt.tablename,
    format('ALTER PUBLICATION supabase_realtime ADD TABLE %I.%I;', pt.schemaname, pt.tablename)
  from pg_publication_tables pt where pt.pubname = 'supabase_realtime'
)
select section, object, ddl from stmts order by section, object;
